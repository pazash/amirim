class _OfflineBoundingBoxRegion:
    """Offline-safe BoundingBoxRegion compatible with EWB's BoundingBoxRegion."""

    def __init__(
        self,
        latitude_min: float,
        latitude_max: float,
        longitude_min: float,
        longitude_max: float,
    ) -> None:
        self.latitude_min = float(latitude_min)
        self.latitude_max = float(latitude_max)
        self.longitude_min = float(longitude_min)
        self.longitude_max = float(longitude_max)

    def mask(self, dataset: xr.Dataset) -> xr.Dataset:
        """Subset *dataset* to [latitude_min, latitude_max] and [longitude_min, longitude_max]."""
        ds_uses_360 = bool(np.any(dataset["longitude"].values > 180))
        lon_min = self.longitude_min % 360 if ds_uses_360 else self.longitude_min
        lon_max = self.longitude_max % 360 if ds_uses_360 else self.longitude_max

        lat_da = dataset.latitude.where(
            (dataset.latitude >= self.latitude_min)
            & (dataset.latitude <= self.latitude_max),
            drop=True,
        )
        if lon_min > lon_max:
            lon_da = dataset.longitude.where(
                (dataset.longitude >= lon_min) | (dataset.longitude <= lon_max),
                drop=True,
            )
        else:
            lon_da = dataset.longitude.where(
                (dataset.longitude >= lon_min) & (dataset.longitude <= lon_max),
                drop=True,
            )
        return dataset.sel(latitude=lat_da, longitude=lon_da)


@dataclass
class _OfflineHeatwaveCase:
    """Metadata container mirroring ExtremeWeatherBench IndividualCase."""

    case_id_number: int
    title: str
    start_date: pd.Timestamp
    end_date: pd.Timestamp
    location: _OfflineBoundingBoxRegion
    event_type: str = "heat_wave"


def prepare_longitude_for_plot(
    ds: xr.Dataset, lon_min: float, lon_max: float
) -> xr.Dataset:
    """
    Normalize dataset longitudes so they remain strictly contiguous for Cartopy
    ``pcolormesh`` plotting, including regions crossing the prime meridian (0°E).

    For bounding boxes with negative western longitudes (e.g. Case 22: -9° to 10°),
    converting to ``[0, 360)`` splits the domain into ``[0..10, 351..359.75]``,
    which stretches ``pcolormesh`` across the globe. Mapping to ``[-180, 180)``
    and sorting preserves a contiguous ``[-9..10]`` grid.
    """
    if "longitude" not in ds.coords:
        return ds
    if lon_min < 0 or lon_max < 0:
        new_lon = ((ds["longitude"] + 180.0) % 360.0) - 180.0
        return ds.assign_coords(longitude=new_lon).sortby("longitude")
    return standardize_longitude(ds)


def _load_case_from_events_yaml(
    case_id: int, years: Sequence[int]
) -> _OfflineHeatwaveCase | None:
    """Fallback loader reading EWB's bundled events.yaml directly offline."""
    spec = importlib.util.find_spec("extremeweatherbench")
    if spec is None or spec.origin is None:
        return None
    yaml_path = Path(spec.origin).resolve().parent / "data" / "events.yaml"
    if not yaml_path.exists():
        return None

    target_years = {int(y) for y in years}
    with yaml_path.open("r", encoding="utf-8") as f:
        raw_events = yaml.safe_load(f) or []

    for entry in raw_events:
        if entry.get("event_type") != "heat_wave":
            continue
        if int(entry.get("case_id_number", -1)) != int(case_id):
            continue
        loc = entry.get("location", {})
        if loc.get("type") != "bounded_region":
            continue
        start_dt = pd.to_datetime(entry["start_date"])
        if target_years and start_dt.year not in target_years:
            continue
        params = loc["parameters"]
        return _OfflineHeatwaveCase(
            case_id_number=int(entry["case_id_number"]),
            title=str(entry["title"]),
            start_date=start_dt,
            end_date=pd.to_datetime(entry["end_date"]),
            location=_OfflineBoundingBoxRegion(
                latitude_min=float(params["latitude_min"]),
                latitude_max=float(params["latitude_max"]),
                longitude_min=float(params["longitude_min"]),
                longitude_max=float(params["longitude_max"]),
            ),
        )
    return None


def get_target_oos_case(
    case_id: int = DEFAULT_CASE_ID,
    years: Sequence[int] = (2022,),
):
    """
    Retrieve the requested out-of-sample ExtremeWeatherBench heatwave case.

    Uses ``get_oos_heatwave_cases(years=years)`` and falls back to EWB's
    bundled ``events.yaml`` if remote EWB initialization is unavailable.
    """
    if get_oos_heatwave_cases is not None:
        try:
            cases = get_oos_heatwave_cases(years=years)
            for c in cases:
                if int(c.case_id_number) == int(case_id):
                    return c
        except Exception as exc:
            logger.warning(
                f"get_oos_heatwave_cases failed ({exc}); falling back to bundled events.yaml."
            )

    fallback = _load_case_from_events_yaml(case_id=case_id, years=years)
    if fallback is not None:
        return fallback

    raise ValueError(
        f"Out-of-sample heatwave case_id={case_id} not found for years={list(years)}."
    )


def find_case_forecast_files(
    forecast_dir: Path,
    case,
    model_key: str = DEFAULT_MODEL_KEY,
    start_leads: Sequence[int] = DEFAULT_START_LEADS,
) -> list[Path]:
    """
    Locate isolated per-case Aurora NetCDF files generated by ``oos_heatwave_evaluator.py``.

    Checks exact synoptic filenames for *start_leads* first, then falls back to
    a per-model, per-case glob pattern.
    """
    aligned_start = align_to_synoptic_12h(case.start_date)
    matched: list[Path] = []
    for lead in start_leads:
        init_t = aligned_start - timedelta(hours=int(lead))
        candidate = forecast_filename(
            forecast_dir, model_key, init_t, int(lead), case.case_id_number
        )
        if candidate.exists():
            matched.append(candidate)

    if matched:
        return sorted(matched)

    return sorted(
        forecast_dir.glob(f"aurora_{model_key}_hw_*_case{case.case_id_number}.nc")
    )


def _format_colorbar_plot(
    ax,
    lon,
    lat,
    values: np.ndarray,
    *,
    title: str,
    vmin: float,
    vmax: float,
) -> None:
    """Render a single 2D temperature panel on a Cartopy GeoAxes."""
    ax.add_feature(cfeature.COASTLINE)
    ax.add_feature(cfeature.BORDERS, linestyle=":")
    im = ax.pcolormesh(
        lon,
        lat,
        values,
        cmap="coolwarm",
        vmin=vmin,
        vmax=vmax,
        transform=ccrs.PlateCarree(),
    )
    ax.set_title(title)
    plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)


def plot_oos_case_maps(
    case_id: int = DEFAULT_CASE_ID,
    model_key: str = DEFAULT_MODEL_KEY,
    forecast_dir: str | Path = DEFAULT_FORECAST_DIR,
    plots_dir: str | Path = DEFAULT_PLOTS_DIR,
    start_leads: Sequence[int] = DEFAULT_START_LEADS,
) -> list[Path]:
    """
    Generate 1x3 spatial 2m temperature maps (Aurora vs. ECMWF HRES vs. ERA5)
    across all matching forecast lead times for a single OOS heatwave case.
    """
    if model_key not in MODEL_CONFIGS:
        raise ValueError(
            f"Unsupported model_key {model_key!r}. Expected one of {tuple(MODEL_CONFIGS)}."
        )

    forecast_path = Path(forecast_dir)
    if not forecast_path.exists():
        logger.error(
            f"Forecast directory {forecast_path.resolve()} not found. "
            f"Generate forecasts first with:\n"
            f"  python scripts/extremes/heatwaves/oos_heatwave_evaluator.py "
            f"--generate --models {model_key} --years 2022"
        )
        return []

    case = get_target_oos_case(case_id=case_id, years=(2022,))
    nc_files = find_case_forecast_files(
        forecast_path, case=case, model_key=model_key, start_leads=start_leads
    )
    if not nc_files:
        logger.error(
            f"No {model_key} forecast files found for Case {case.case_id_number} ({case.title}) "
            f"in {forecast_path.resolve()}.\n"
            f"Generate them first with:\n"
            f"  python scripts/extremes/heatwaves/oos_heatwave_evaluator.py "
            f"--generate --models {model_key} --years 2022"
        )
        return []

    case_out_dir = Path(plots_dir) / f"event_{case.case_id_number}"
    case_out_dir.mkdir(parents=True, exist_ok=True)

    aligned_start = align_to_synoptic_12h(case.start_date)
    end_dt = pd.to_datetime(case.end_date)
    lon_min = float(case.location.longitude_min)
    lon_max = float(case.location.longitude_max)
    lat_min = float(case.location.latitude_min)
    lat_max = float(case.location.latitude_max)

    logger.info(
        f"Loading ARCO ERA5 and WB2 HRES for Case {case.case_id_number} ({case.title}) "
        f"[{aligned_start} -> {end_dt}]..."
    )
    era5_ds = load_era5_zarr(variable="temperature")
    hres_ds = load_hres_zarr(variable="temperature")

    era5_case_raw = era5_ds.sel(
        time=slice(aligned_start.to_pydatetime(), end_dt.to_pydatetime())
    )
    six_hr_mask = era5_case_raw.time.dt.hour.isin([0, 6, 12, 18])
    era5_case_raw = era5_case_raw.isel(time=np.where(six_hr_mask.values)[0])
    era5_case = case.location.mask(era5_case_raw).compute()
    era5_case = prepare_longitude_for_plot(era5_case, lon_min, lon_max)
    del era5_case_raw

    model_label = MODEL_TITLE_LABELS.get(model_key, f"Aurora ({model_key})")
    saved_paths: list[Path] = []

    logger.info(
        f"Found {len(nc_files)} {model_key} forecast files for Case {case.case_id_number}."
    )

    for nc_file in nc_files:
        logger.info(f"Processing {nc_file.name}...")
        with xr.open_dataset(nc_file) as aurora_raw:
            init_t = pd.to_datetime(aurora_raw.init_time.values[0])
            aurora_fcst = case.location.mask(aurora_raw).compute()

        aurora_fcst = prepare_longitude_for_plot(aurora_fcst, lon_min, lon_max)
        aurora_var = (
            "2t_aurora"
            if "2t_aurora" in aurora_fcst.data_vars
            else [
                v
                for v in aurora_fcst.data_vars
                if v not in ("latitude", "longitude")
            ][0]
        )

        # Fetch HRES initialized at exact init_t (falling back to pad if needed)
        hres_fcst = None
        hres_init_t = init_t
        hres_raw = None
        try:
            hres_raw = hres_ds.sel(init_time=init_t.to_datetime64())
            hres_init_t = pd.to_datetime(hres_raw.init_time.values)
        except (KeyError, IndexError):
            try:
                hres_raw = hres_ds.sel(init_time=init_t.to_datetime64(), method="pad")
                hres_init_t = pd.to_datetime(hres_raw.init_time.values)
            except (KeyError, IndexError):
                hres_raw = None
                logger.warning(f"  No matching HRES forecast found for init_time={init_t}")

        if hres_raw is not None:
            if np.issubdtype(hres_raw.lead_time.dtype, np.timedelta64):
                hres_lead_td = pd.to_timedelta(hres_raw.lead_time.values)
            else:
                hres_lead_td = pd.to_timedelta(hres_raw.lead_time.values, unit="h")
            hres_valid_times = hres_init_t + hres_lead_td
            in_window = np.asarray(
                (hres_valid_times >= aligned_start) & (hres_valid_times <= end_dt)
            )
            if np.any(in_window):
                hres_slice = hres_raw.isel(lead_time=np.where(in_window)[0])
                hres_fcst = case.location.mask(hres_slice).compute()
                hres_fcst = prepare_longitude_for_plot(hres_fcst, lon_min, lon_max)
            del hres_raw

        for lt in aurora_fcst.lead_time.values:
            lt_hours = timedelta_to_hours(lt)
            if lt_hours > 240:
                continue
            valid_time = init_t + timedelta(hours=lt_hours)
            if not (aligned_start <= valid_time <= end_dt):
                continue

            try:
                tgt_2d = era5_case["surface_air_temperature"].sel(
                    time=valid_time.to_pydatetime()
                )
            except KeyError:
                continue

            fcst_2d_aurora = aurora_fcst[aurora_var].sel(
                init_time=aurora_fcst.init_time.values[0], lead_time=lt
            ).squeeze()
            aurora_val = fcst_2d_aurora.values.squeeze() - 273.15
            tgt_val = tgt_2d.values.squeeze() - 273.15

            fcst_2d_hres = None
            hres_val = None
            if hres_fcst is not None:
                hres_lt_hours = timedelta_to_hours(valid_time - hres_init_t)
                try:
                    fcst_2d_hres = _select_hres_lead(hres_fcst, hres_lt_hours).squeeze()
                    hres_val = fcst_2d_hres.values.squeeze() - 273.15
                except KeyError:
                    fcst_2d_hres = None
                    hres_val = None

            finite_arrays = [
                arr
                for arr in (aurora_val, hres_val, tgt_val)
                if arr is not None and not np.isnan(arr).all()
            ]
            if finite_arrays:
                vmin = min(float(np.nanmin(arr)) for arr in finite_arrays)
                vmax = max(float(np.nanmax(arr)) for arr in finite_arrays)
            else:
                vmin, vmax = 0.0, 1.0
            if vmin == vmax:
                vmax = vmin + 1.0

            fig, axes = plt.subplots(
                1, 3, figsize=(20, 6), subplot_kw={"projection": ccrs.PlateCarree()}
            )
            plt.subplots_adjust(wspace=0.3)

            init_str = init_t.strftime("%Y-%m-%d %H:%M")
            valid_str = valid_time.strftime("%Y-%m-%d %H:%M")
            fig.suptitle(
                f"OOS Heatwave Case {case.case_id_number} ({case.title}) - "
                f"Init: {init_str} | Valid: {valid_str} (Lead: {lt_hours}h)",
                fontsize=15,
            )

            _format_colorbar_plot(
                axes[0],
                fcst_2d_aurora.longitude,
                fcst_2d_aurora.latitude,
                aurora_val,
                title=f"{model_label} (°C)",
                vmin=vmin,
                vmax=vmax,
            )

            if fcst_2d_hres is not None and hres_val is not None:
                _format_colorbar_plot(
                    axes[1],
                    fcst_2d_hres.longitude,
                    fcst_2d_hres.latitude,
                    hres_val,
                    title="ECMWF HRES (°C)",
                    vmin=vmin,
                    vmax=vmax,
                )
            else:
                axes[1].add_feature(cfeature.COASTLINE)
                axes[1].add_feature(cfeature.BORDERS, linestyle=":")
                axes[1].set_title("ECMWF HRES (Data Unavailable)")

            _format_colorbar_plot(
                axes[2],
                tgt_2d.longitude,
                tgt_2d.latitude,
                tgt_val,
                title="ERA5 (°C)",
                vmin=vmin,
                vmax=vmax,
            )

            for ax in axes:
                ax.set_extent([lon_min, lon_max, lat_min, lat_max], crs=ccrs.PlateCarree())

            out_name = f"init_{init_t.strftime('%Y%m%d%H')}_lt_{lt_hours:03d}.png"
            out_path = case_out_dir / out_name
            plt.savefig(out_path, bbox_inches="tight", dpi=150)
            plt.close(fig)
            saved_paths.append(out_path)
            logger.info(f"  Saved {out_name}")

        del aurora_fcst
        if hres_fcst is not None:
            del hres_fcst
        gc.collect()

    del era5_case
    gc.collect()
    logger.info(f"Saved {len(saved_paths)} map figures to {case_out_dir.resolve()}")
    return saved_paths


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parse CLI arguments for out-of-sample heatwave map generation."""
    parser = argparse.ArgumentParser(
        description=(
            "Plot 1x3 spatial temperature comparison maps (Aurora 0.25° vs. ECMWF HRES "
            "vs. ERA5) for an out-of-sample heatwave case."
        )
    )
    parser.add_argument(
        "--case-id",
        type=int,
        default=DEFAULT_CASE_ID,
        help="ExtremeWeatherBench 2022 heatwave case ID (default: 22, 2022 France / Western Med).",
    )
    parser.add_argument(
        "--model",
        type=str,
        choices=list(MODEL_CONFIGS.keys()),
        default=DEFAULT_MODEL_KEY,
        help="Aurora 0.25° model key to plot (default: finetuned).",
    )
    parser.add_argument(
        "--forecast-dir",
        type=Path,
        default=DEFAULT_FORECAST_DIR,
        help="Directory containing per-case NetCDF forecasts (default: ewb_oos_hw_forecasts).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_PLOTS_DIR,
        help="Output directory for generated map PNGs (default: plots/oos_heatwave_maps).",
    )
    parser.add_argument(
        "--start-leads",
        type=int,
        nargs="+",
        default=list(DEFAULT_START_LEADS),
        help="Onset lead-time buckets in hours to include (default: 24 72 120).",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    """CLI entrypoint."""
    args = parse_args(argv)
    plot_oos_case_maps(
        case_id=args.case_id,
        model_key=args.model,
        forecast_dir=args.forecast_dir,
        plots_dir=args.output_dir,
        start_leads=args.start_leads,
    )


if __name__ == "__main__":
    main()
