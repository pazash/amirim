"""
Plot Gradient-Based & Integrated Gradients (IG) Saliency Maps for Weather Prediction in Israel.

Reads the saliency NetCDF generated by `scripts/compute_israel_saliency.py` or
`scripts/compute_israel_ig_saliency.py` and creates:
  1. Individual global saliency maps for each lead time in [6, 24, 72, 120] hours.
  2. Individual synoptic regional maps (Europe / Mediterranean / Middle East / North Africa)
     for each lead time in [6, 24, 72, 120] hours.
  3. A 2x2 multi-panel global saliency comparison across all 4 lead times.
  4. A 2x2 multi-panel synoptic regional comparison across all 4 lead times.
  5. Optional 4x2 side-by-side Vanilla Gradient vs. Integrated Gradients comparison figures
     (when `--compare-ig-nc` is supplied).

Usage:
    python scripts/plot_israel_saliency_maps.py [--saliency-nc saliency_outputs/israel_saliency_mean.nc]
    python scripts/plot_israel_saliency_maps.py --saliency-nc saliency_outputs/israel_saliency_mean.nc \
        --compare-ig-nc saliency_outputs_ig/israel_ig_saliency_mean.nc
"""

from __future__ import annotations

import argparse
import logging
import warnings
from pathlib import Path

import matplotlib.colors as mcolors
import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import xarray as xr

try:
    import cartopy.crs as ccrs
    import cartopy.feature as cfeature

    HAS_CARTOPY = True
except ImportError:
    ccrs = None
    cfeature = None
    HAS_CARTOPY = False

warnings.filterwarnings("ignore")

logger = logging.getLogger(__name__)
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)

ISRAEL_BBOX = {
    "lat_min": 29.5,
    "lat_max": 33.5,
    "lon_min": 34.25,
    "lon_max": 35.75,
}

# Wider synoptic window around Israel (Atlantic / Europe / Mediterranean / Middle East)
SYNOPTIC_EXTENT = [-25.0, 65.0, 12.0, 62.0]  # [lon_min, lon_max, lat_min, lat_max]

LEAD_TIMES_H = [6, 24, 72, 120]


def _wrap_lon_to_180(da: xr.DataArray) -> xr.DataArray:
    """Convert longitude coordinates from [0, 360) to [-180, 180) and sort."""
    lon_180 = ((da.longitude.values + 180.0) % 360.0) - 180.0
    da = da.assign_coords(longitude=lon_180).sortby("longitude")
    return da


def _draw_israel_box(ax: plt.Axes, edgecolor: str = "cyan", linewidth: float = 1.6) -> None:
    """Draw the Israel target bounding box on a map axis."""
    width = ISRAEL_BBOX["lon_max"] - ISRAEL_BBOX["lon_min"]
    height = ISRAEL_BBOX["lat_max"] - ISRAEL_BBOX["lat_min"]
    kwargs = {}
    if HAS_CARTOPY:
        kwargs["transform"] = ccrs.PlateCarree()
    rect = mpatches.Rectangle(
        (ISRAEL_BBOX["lon_min"], ISRAEL_BBOX["lat_min"]),
        width,
        height,
        linewidth=linewidth,
        edgecolor=edgecolor,
        facecolor="none",
        zorder=10,
        label="Israel Target BBox",
        **kwargs,
    )
    ax.add_patch(rect)


def _format_map_axes(
    ax: plt.Axes,
    extent: list[float] | None = None,
    draw_labels: bool = True,
) -> None:
    """Add coastlines, borders, and gridlines to a map axis."""
    if HAS_CARTOPY:
        ax.add_feature(cfeature.COASTLINE, linewidth=0.6, edgecolor="#333333")
        ax.add_feature(cfeature.BORDERS, linestyle=":", linewidth=0.4, edgecolor="#555555")
        if extent is not None:
            ax.set_extent(extent, crs=ccrs.PlateCarree())
        else:
            ax.set_global()

        gl = ax.gridlines(
            crs=ccrs.PlateCarree(),
            draw_labels=draw_labels,
            linewidth=0.4,
            color="gray",
            alpha=0.4,
            linestyle="--",
        )
        gl.top_labels = False
        gl.right_labels = False
    else:
        if extent is not None:
            ax.set_xlim(extent[0], extent[1])
            ax.set_ylim(extent[2], extent[3])
        else:
            ax.set_xlim(-180.0, 180.0)
            ax.set_ylim(-90.0, 90.0)
        ax.grid(True, linewidth=0.4, color="gray", alpha=0.4, linestyle="--")
        if draw_labels:
            ax.set_xlabel("Longitude (°E)")
            ax.set_ylabel("Latitude (°N)")


def _get_log_norm(arr_list: list[np.ndarray], dynamic_range_decades: float = 3.5) -> mcolors.LogNorm:
    """
    Create a LogNorm spanning `dynamic_range_decades` orders of magnitude below the
    global maximum across the provided arrays so both localized peaks and synoptic
    structures are clearly visible.
    """
    vmax = float(max(np.nanmax(a) for a in arr_list))
    if vmax <= 0.0:
        vmax = 1.0
    vmin = max(vmax * (10.0 ** (-dynamic_range_decades)), 1e-12)
    return mcolors.LogNorm(vmin=vmin, vmax=vmax)


def _resolve_method_labels(ds: xr.Dataset, nc_path: Path | None = None) -> tuple[str, str]:
    """Return `(method_title, cbar_label)` based on dataset attributes or filename."""
    is_ig = (
        ds.attrs.get("saliency_method") == "integrated_gradients"
        or (nc_path is not None and "_ig_" in nc_path.name.lower())
    )
    if is_ig:
        ig_steps = ds.attrs.get("ig_steps", 8)
        return (
            f"Integrated Gradients (M={ig_steps})",
            r"IG Attribution $\|(X_0 - X_{\mathrm{base}}) \odot \overline{\nabla}_{X_0} Y_{\mathrm{Israel}}\|_2$",
        )
    return (
        "Gradient Saliency",
        r"Gradient Saliency $\|\nabla_{X_0} Y_{\mathrm{Israel}}\|_2$",
    )


def plot_single_lead_time_map(
    da_2d: xr.DataArray,
    lt_h: int,
    out_file: Path,
    extent: list[float] | None = None,
    title_prefix: str = "Global",
    method_title: str = "Gradient Saliency",
    cbar_label: str = r"Gradient Saliency $\|\nabla_{X_0} Y_{\mathrm{Israel}}\|_2$",
    cmap: str = "inferno",
) -> None:
    """Plot and save a single 2D saliency map for one lead time."""
    subplot_kw = {"projection": ccrs.PlateCarree()} if HAS_CARTOPY else {}
    fig, ax = plt.subplots(
        1,
        1,
        figsize=(11, 6) if extent is None else (10, 6.5),
        subplot_kw=subplot_kw,
    )

    vals = np.maximum(da_2d.values, 1e-15)
    norm = _get_log_norm([vals], dynamic_range_decades=3.5)

    mesh_kwargs = {"transform": ccrs.PlateCarree()} if HAS_CARTOPY else {}
    im = ax.pcolormesh(
        da_2d.longitude.values,
        da_2d.latitude.values,
        vals,
        cmap=cmap,
        norm=norm,
        shading="auto",
        **mesh_kwargs,
    )

    _format_map_axes(ax, extent=extent, draw_labels=True)
    _draw_israel_box(ax, edgecolor="cyan", linewidth=1.8)

    cbar = fig.colorbar(im, ax=ax, orientation="vertical", fraction=0.03, pad=0.03)
    cbar.set_label(f"{cbar_label} (log scale)", fontsize=11)

    ax.set_title(
        f"Aurora 0.25° {title_prefix} {method_title} for Israel (t, q, u, v, z) — Lead Time: +{lt_h}h",
        fontsize=13,
        pad=12,
    )

    fig.savefig(out_file, bbox_inches="tight", dpi=220)
    plt.close(fig)
    logger.info(f"  Saved → {out_file}")


def plot_four_panel_comparison(
    ds: xr.Dataset,
    var_key: str,
    lead_times_h: list[int],
    out_file: Path,
    extent: list[float] | None = None,
    title_prefix: str = "Global",
    method_title: str = "Gradient Saliency",
    cbar_label: str = r"Gradient Saliency $\|\nabla_{X_0} Y_{\mathrm{Israel}}\|_2$",
    cmap: str = "inferno",
) -> None:
    """Plot a 2x2 comparison figure across [6, 24, 72, 120]h lead times."""
    subplot_kw = {"projection": ccrs.PlateCarree()} if HAS_CARTOPY else {}
    fig, axes = plt.subplots(
        2,
        2,
        figsize=(16, 10) if extent is None else (15, 10.5),
        subplot_kw=subplot_kw,
    )
    plt.subplots_adjust(wspace=0.14, hspace=0.22)
    axes_flat = axes.ravel()

    slices: list[xr.DataArray] = []
    for lt_h in lead_times_h:
        da = ds[var_key].sel(lead_time=pd.to_timedelta(f"{lt_h}h")).squeeze()
        da = _wrap_lon_to_180(da)
        slices.append(da)

    norm = _get_log_norm([np.maximum(s.values, 1e-15) for s in slices], dynamic_range_decades=3.5)

    mesh_kwargs = {"transform": ccrs.PlateCarree()} if HAS_CARTOPY else {}
    im = None
    for idx, (lt_h, da_2d) in enumerate(zip(lead_times_h, slices)):
        ax = axes_flat[idx]
        vals = np.maximum(da_2d.values, norm.vmin)

        im = ax.pcolormesh(
            da_2d.longitude.values,
            da_2d.latitude.values,
            vals,
            cmap=cmap,
            norm=norm,
            shading="auto",
            **mesh_kwargs,
        )
        _format_map_axes(ax, extent=extent, draw_labels=True)
        _draw_israel_box(ax, edgecolor="cyan", linewidth=1.6)

        max_pos = np.unravel_index(np.argmax(da_2d.values), da_2d.shape)
        peak_lat = float(da_2d.latitude.values[max_pos[0]])
        peak_lon = float(da_2d.longitude.values[max_pos[1]])
        ax.set_title(
            f"Lead Time: +{lt_h}h ({lt_h // 6} AR steps)  |  "
            f"Peak: ({peak_lat:.1f}°N, {peak_lon:.1f}°E)",
            fontsize=11.5,
        )

    assert im is not None
    cbar = fig.colorbar(
        im,
        ax=axes.ravel().tolist(),
        orientation="horizontal",
        fraction=0.04,
        pad=0.06,
        aspect=45,
    )
    cbar.set_label(
        f"{cbar_label} across (t, q, u, v, z & 13 levels)",
        fontsize=12,
    )

    num_dates = ds.attrs.get("num_dates", 1)
    fig.suptitle(
        f"Aurora 0.25° {title_prefix} {method_title} for Israel Weather Prediction\n"
        f"(Atmospheric Variables: t, q, u, v, z  |  Averaged over {num_dates} Seasonal Evaluation Dates)",
        fontsize=14,
        y=0.98,
    )

    fig.savefig(out_file, bbox_inches="tight", dpi=220)
    plt.close(fig)
    logger.info(f"  Saved → {out_file}")


def plot_vanilla_vs_ig_comparison(
    vanilla_nc: str,
    ig_nc: str,
    plots_dir: str = "plots/israel_ig_saliency",
    var_key: str = "saliency_l2",
    cmap: str = "inferno",
) -> None:
    """
    Plot 4x2 side-by-side comparison figures (rows = [6, 24, 72, 120]h, cols = Vanilla vs. IG)
    for both Global and Synoptic Regional extents, normalized to [10^-3.5, 1] relative to each
    panel's maximum so spatial conciseness and structural differences are directly comparable.
    """
    van_path = Path(vanilla_nc)
    ig_path = Path(ig_nc)
    if not van_path.exists() or not ig_path.exists():
        raise FileNotFoundError(
            f"Both vanilla_nc ({van_path}) and ig_nc ({ig_path}) must exist for comparison."
        )

    out_dir = Path(plots_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    with xr.open_dataset(van_path, engine="h5netcdf") as ds_van, \
         xr.open_dataset(ig_path, engine="h5netcdf") as ds_ig:
        if "init_time" in ds_van.dims:
            ds_van = ds_van.mean(dim="init_time", keep_attrs=True)
        if "init_time" in ds_ig.dims:
            ds_ig = ds_ig.mean(dim="init_time", keep_attrs=True)

        ig_steps = ds_ig.attrs.get("ig_steps", 8)

        for scope_tag, extent, title_prefix in [
            ("global", None, "Global"),
            ("synoptic", SYNOPTIC_EXTENT, "Synoptic Regional"),
        ]:
            subplot_kw = {"projection": ccrs.PlateCarree()} if HAS_CARTOPY else {}
            fig, axes = plt.subplots(
                len(LEAD_TIMES_H),
                2,
                figsize=(15, 4.2 * len(LEAD_TIMES_H)),
                subplot_kw=subplot_kw,
            )
            plt.subplots_adjust(wspace=0.14, hspace=0.26)

            norm = mcolors.LogNorm(vmin=10.0 ** (-3.5), vmax=1.0)
            mesh_kwargs = {"transform": ccrs.PlateCarree()} if HAS_CARTOPY else {}
            im = None

            for row_idx, lt_h in enumerate(LEAD_TIMES_H):
                lt_delta = pd.to_timedelta(f"{lt_h}h")
                da_van = _wrap_lon_to_180(ds_van[var_key].sel(lead_time=lt_delta).squeeze())
                da_ig = _wrap_lon_to_180(ds_ig[var_key].sel(lead_time=lt_delta).squeeze())

                for col_idx, (da_2d, col_label) in enumerate(
                    [
                        (da_van, "Vanilla Gradient Saliency"),
                        (da_ig, f"Integrated Gradients (M={ig_steps}, ERA5 Climatology Baseline)"),
                    ]
                ):
                    ax = axes[row_idx, col_idx]
                    max_val = float(np.nanmax(da_2d.values))
                    rel_vals = da_2d.values / max(max_val, 1e-15)
                    rel_vals = np.clip(rel_vals, norm.vmin, 1.0)

                    im = ax.pcolormesh(
                        da_2d.longitude.values,
                        da_2d.latitude.values,
                        rel_vals,
                        cmap=cmap,
                        norm=norm,
                        shading="auto",
                        **mesh_kwargs,
                    )
                    _format_map_axes(ax, extent=extent, draw_labels=True)
                    _draw_israel_box(ax, edgecolor="cyan", linewidth=1.5)
                    ax.set_title(f"{col_label} — Lead: +{lt_h}h", fontsize=11)

            assert im is not None
            cbar = fig.colorbar(
                im,
                ax=axes.ravel().tolist(),
                orientation="horizontal",
                fraction=0.025,
                pad=0.04,
                aspect=50,
            )
            cbar.set_label(
                "Peak-Normalized Saliency / Attribution (log scale, relative to lead-time max)",
                fontsize=12,
            )
            fig.suptitle(
                f"Aurora 0.25° {title_prefix}: Vanilla Gradient Saliency vs. Integrated Gradients for Israel",
                fontsize=14,
                y=0.995,
            )

            out_file = out_dir / f"israel_vanilla_vs_ig_{scope_tag}.png"
            fig.savefig(out_file, bbox_inches="tight", dpi=220)
            plt.close(fig)
            logger.info(f"  Saved comparison → {out_file}")


def plot_all_saliency_maps(
    saliency_nc: str = "saliency_outputs/israel_saliency_mean.nc",
    plots_dir: str = "plots/israel_saliency",
    var_key: str = "saliency_l2",
) -> None:
    """Generate all global and synoptic saliency maps from a saved saliency NetCDF."""
    nc_path = Path(saliency_nc)
    if not nc_path.exists():
        raise FileNotFoundError(
            f"Saliency NetCDF not found at {nc_path}. Run compute_israel_saliency.py or compute_israel_ig_saliency.py first."
        )

    out_dir = Path(plots_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Loading saliency dataset from {nc_path}...")
    with xr.open_dataset(nc_path, engine="h5netcdf") as ds:
        if "init_time" in ds.dims:
            ds = ds.mean(dim="init_time", keep_attrs=True)

        method_title, cbar_label = _resolve_method_labels(ds, nc_path)

        # 1. Individual lead-time maps (Global and Synoptic Zoom)
        for lt_h in LEAD_TIMES_H:
            da_2d = ds[var_key].sel(lead_time=pd.to_timedelta(f"{lt_h}h")).squeeze()
            da_2d = _wrap_lon_to_180(da_2d)

            plot_single_lead_time_map(
                da_2d=da_2d,
                lt_h=lt_h,
                out_file=out_dir / f"israel_saliency_global_lt{lt_h:03d}h.png",
                extent=None,
                title_prefix="Global",
                method_title=method_title,
                cbar_label=cbar_label,
            )
            plot_single_lead_time_map(
                da_2d=da_2d,
                lt_h=lt_h,
                out_file=out_dir / f"israel_saliency_synoptic_lt{lt_h:03d}h.png",
                extent=SYNOPTIC_EXTENT,
                title_prefix="Synoptic Regional",
                method_title=method_title,
                cbar_label=cbar_label,
            )

        # 2. 2x2 Multi-panel comparison figures (Global and Synoptic Zoom)
        plot_four_panel_comparison(
            ds=ds,
            var_key=var_key,
            lead_times_h=LEAD_TIMES_H,
            out_file=out_dir / "israel_saliency_global_4panel.png",
            extent=None,
            title_prefix="Global",
            method_title=method_title,
            cbar_label=cbar_label,
        )
        plot_four_panel_comparison(
            ds=ds,
            var_key=var_key,
            lead_times_h=LEAD_TIMES_H,
            out_file=out_dir / "israel_saliency_synoptic_4panel.png",
            extent=SYNOPTIC_EXTENT,
            title_prefix="Synoptic Regional",
            method_title=method_title,
            cbar_label=cbar_label,
        )

    logger.info(f"All saliency maps saved to {out_dir.resolve()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Plot global and regional gradient-based or IG saliency maps for Israel weather prediction."
    )
    parser.add_argument(
        "--saliency-nc",
        default="saliency_outputs/israel_saliency_mean.nc",
        help="Path to the saliency NetCDF file produced by compute_israel_saliency.py or compute_israel_ig_saliency.py",
    )
    parser.add_argument(
        "--compare-ig-nc",
        default=None,
        help="Optional path to an Integrated Gradients NetCDF to plot side-by-side against --saliency-nc.",
    )
    parser.add_argument(
        "--plots-dir",
        default="plots/israel_saliency",
        help="Output directory for generated map figures.",
    )
    parser.add_argument(
        "--metric",
        choices=["saliency_l2", "saliency_mag"],
        default="saliency_l2",
        help="Saliency aggregation metric to plot (default: saliency_l2).",
    )
    args = parser.parse_args()

    plot_all_saliency_maps(
        saliency_nc=args.saliency_nc,
        plots_dir=args.plots_dir,
        var_key=args.metric,
    )

    if args.compare_ig_nc:
        plot_vanilla_vs_ig_comparison(
            vanilla_nc=args.saliency_nc,
            ig_nc=args.compare_ig_nc,
            plots_dir=args.plots_dir,
            var_key=args.metric,
        )
